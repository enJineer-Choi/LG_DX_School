-- 급여가 5000이하인 사람들의 사번, FIRST_NAME,급여를 출력
SELECT EMPLOYEE_ID,FIRST_NAME,SALARY FROM EMPLOYEES
WHERE SALARY <=5000;

-- 연봉이 50000이상인 사람들의 사번, FIRST_NAME,연봉 출력
SELECT EMPLOYEE_ID,FIRST_NAME,SALARY*12 AS "연봉"  FROM EMPLOYEES
WHERE SALARY*12 >=50000;

-- 연봉이 50000이상인 사람들의 사번, FIRST_NAME,연봉 출력
-- 실행 순서상 WHERE가 SELECT 보다 먼저 실행되므로 에러가 발생
SELECT EMPLOYEE_ID,FIRST_NAME,SALARY*12 AS "연봉"  FROM EMPLOYEES
WHERE "연봉" >=50000;




-- JOB_ID가 'IT_PROG'인 직원의 사번, FIRST_NAME,JOB_ID 출력
SELECT EMPLOYEE_ID,FIRST_NAME,JOB_ID FROM EMPLOYEES
WHERE JOB_ID = 'IT_PROG';
-- 명령어는 대소문자 구분 안하지만, 값은 대소문자를 구분한다!
-- 따옴표와 쌍따옴표 구분함 > 데이터에 관련된 값을 조회할때는 ''를 써야함

-- JOB_ID가 'IT_PROG'이 아닌 직원의 사번, FIRST_NAME,JOB_ID 출력
SELECT EMPLOYEE_ID,FIRST_NAME,JOB_ID FROM EMPLOYEES
WHERE JOB_ID != 'IT_PROG';

-- 부서번호가 90이고, 급여가 5000이상인 직원의 사번, FIRST_NAM,E 급여 출력
SELECT EMPLOYEE_ID,FIRST_NAME,SALARY FROM EMPLOYEES
WHERE DEPARTMENT_ID =90 AND SALARY >=5000;

-- 100번째 부서에서 근무하거나 60번째 부서에서 근무하는 직원들의 사번, FIRST_NAME,부서번호 출ㄹ력
SELECT EMPLOYEE_ID,FIRST_NAME,DEPARTMENT_ID FROM EMPLOYEES
WHERE DEPARTMENT_ID = 100 OR DEPARTMENT_ID = 60;


-- jOB ID 가 IT_PROG이 아니고, FI_ACCOUNT가 아닌 직원들의 사번과  JOB_ID출력
SELECT EMPLOYEE_ID,JOB_ID FROM EMPLOYEES
WHERE JOB_ID != 'IT_PROG' AND JOB_ID !='FI_ACCOUNT';

-- 100번째 부서에서 근무하거나 50번째 부서에서 근무하는 직원중에서 연봉이 100000이상인 직원의 사번, FIRST_NAME,연봉출력
SELECT EMPLOYEE_ID,FIRST_NAME,SALARY*12 AS "연봉", DEPARTMENT_ID FROM EMPLOYEES
WHERE (DEPARTMENT_ID = 100 AND SALARY*12 >=100000) OR (DEPARTMENT_ID = 50 AND SALARY*12 >=100000);

-- 이 계산법이 문제 요구조건 + 더 간결한 내용인 것 같다!
SELECT EMPLOYEE_ID,FIRST_NAME,SALARY*12 AS "연봉", DEPARTMENT_ID FROM EMPLOYEES
WHERE (DEPARTMENT_ID = 100 OR DEPARTMENT_ID = 50) AND SALARY*12 >=100000;

-- 부서번호가 30,50,90 들 중 하나인 직원의 사번, 부서번호를 출력
SELECT EMPLOYEE_ID,DEPARTMENT_ID FROM EMPLOYEES
WHERE DEPARTMENT_ID = 30 OR DEPARTMENT_ID = 50 OR DEPARTMENT_ID = 90;


-- 코드가 너무 길어짐 > IN 연산 활용
-- IN :OR의 집합연산 
SELECT EMPLOYEE_ID,DEPARTMENT_ID FROM EMPLOYEES
WHERE DEPARTMENT_ID IN (30,50,90 );

-- NOT을 붙이면 AND 연산으로 바뀜 > 30도 아니고, 50도 아니고, 90도 아님.
SELECT EMPLOYEE_ID,DEPARTMENT_ID FROM EMPLOYEES
WHERE DEPARTMENT_ID NOT IN (30,50,90 );

-- JOB_ID가 'AD_VP'이거나 'ST_MAN'인 사람의 FIRST_NAME,JOB_ID 를 출력

SELECT FIRST_NAME,JOB_ID FROM EMPLOYEES
WHERE JOB_ID IN ('AD_VP','ST_MAN');


-- MANAGER_ID가 145,146,147,148,149 가 아닌 직원 사번과 , MANGER_ID를 출력
