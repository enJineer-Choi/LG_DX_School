-- BETWEEN A AND B : 연속된 범위를 통해서 조건을 걸어줄 때 사용
-- 급여가 10000 대인 직원의 사번과 급여 출력
SELECT EMPLOYEE_ID, SALARY FROM EMPLOYEES
WHERE SALARY BETWEEN 10000 AND 19999;

-- 2005년도 입사 
SELECT FIRST_NAME, HIRE_DATE FROM EMPLOYEES
WHERE HIRE_DATE BETWEEN '05/01/01' AND '05/12/31';

-- 문자열 비교 검색 연산 
-- LIKE 연산과 %(글자수 제한 없음) , _(글자수 의미)
-- FIRST_NAME 'A'로 시작하는 직워들의 이름을 출력ㄱ
SELECT FIRST_NAME FROM EMPLOYEES
WHERE FIRST_NAME LIKE 'A%';

-- FIRST_NAME 'e'로 끝나는 직워들의 이름을 출력ㄱ
SELECT FIRST_NAME FROM EMPLOYEES
WHERE FIRST_NAME LIKE '%e';

-- FIRST_NAME 'e'가 들어간 직워들의 이름을 출력ㄱ
SELECT FIRST_NAME FROM EMPLOYEES
WHERE FIRST_NAME LIKE '%e%';


-- 
-- FIRST_NAME 'A'로 시작하는 이름이 4글자인 직워들의 이름을 출력ㄱ
SELECT FIRST_NAME FROM EMPLOYEES
WHERE FIRST_NAME LIKE 'A___';


-- FIRST_NAME에서 두번째 글자가 e인 사람의 이름을 출력
SELECT FIRST_NAME FROM EMPLOYEES
WHERE FIRST_NAME LIKE '_e%';

-- 이름이 'S'로 시작하고 'n'으로 끝나는 직원의 이름을 출력
SELECT FIRST_NAME FROM EMPLOYEES
WHERE FIRST_NAME LIKE 'S%n';

