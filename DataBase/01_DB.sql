 SELECT 문법 : 데이터 조회시 사용
 SELECT : 어떤거를 조회할건지? *: (all) 전부다 조회한다는 뜻
SELECT * FROM employees;
SELECT EMPLOYEE_ID FROM EMPLOYEES;


-- 실행순서
--1. FROM 실행 : 데이터를 먼저 가져와야함
--2. SELECT 실행 : 그 다음에 원하는 부분을 SELECT!


-- 부서테이블의 모든 정보를 출력
SELECT * FROM DEPARTMENTS;

-- 직원의 사번과 급여 정보 출력
SELECT EMPLOYEE_ID,SALARY FROM EMPLOYEES;

-- 사번,

SELECT EMPLOYEE_ID,FIRST_NAME,HIRE_DATE FROM EMPLOYEES;

-- 부서번호, 부서명, 부서위치번호를 출력
SELECT DEPARTMENT_ID,DEPARTMENT_NAME,LOCATION_ID FROM DEPARTMENTS;

-- 모든 직원의 연봉을 출력 해주세요
SELECT SALARY*12 FROM EMPLOYEES;

-- 별칭 붙여주기
SELECT SALARY*12 AS "YEAR_SALARY" FROM EMPLOYEES;

-- 직원의 입사일과 입사 다음날 
-- SELECT HIRE_DATE , HIRE_DATE+1 AS  "입사일","입사일 다음 날" FROM EMPLOYEES; 이러면 에러남!
SELECT HIRE_DATE AS "입사일", HIRE_DATE+1 AS "입사일 다음 날" FROM EMPLOYEES;

-- 줄바꿈 가능! ";" 콜론 덕분에 줄의 끝마침을 알아서 파악
SELECT HIRE_DATE AS "입사일", HIRE_DATE+1 AS "입사일 다음 날"
FROM EMPLOYEES;



