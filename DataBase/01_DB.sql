-- WHERE절 : 테이블에 있는 "모든행에" 조건을 걸어주는 명령
-- 사번이 100인 직원의 FIRST_NAME 출력

SELECT FIRST_NAME FROM EMPLOYEES
WHERE EMPLOYEE_ID = 100;

-- 60번째 부서에서 근무하는 직원의 사번, 급여 출력

